"""Result objects returned by numerica solvers."""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from numpy.typing import ArrayLike


@dataclass(frozen=True, slots=True)
class RootResult:
    """Outcome of a scalar root finder or fixed-point iteration.

    Attributes
    ----------
    root :
        Estimated solution.
    iterations :
        Iterations performed. Zero means the initial guess already satisfied
        the residual test.
    converged :
        Whether the stopping test succeeded. A returned result has this flag
        set to ``False`` only when ``raise_on_failure=False``.
    residual :
        Absolute residual at ``root``.
    tolerance :
        Tolerance supplied by the caller.
    method :
        Algorithm name.
    history :
        Approximations generated by the iteration, ending at ``root``.
    """

    root: float
    iterations: int
    converged: bool
    residual: float
    tolerance: float
    method: str
    history: tuple[float, ...]

    def __str__(self) -> str:
        status = "converged" if self.converged else "not converged"
        return (
            f"{self.method} ({status}): root={self.root:.12g}, "
            f"iterations={self.iterations}, residual={self.residual:.3e}, "
            f"tolerance={self.tolerance:.3e}"
        )


@dataclass(frozen=True, slots=True)
class IntegralResult:
    """Value of a definite integral.

    Adaptive routines fill ``iterations``, ``residual`` and ``tolerance``.
    Fixed-panel rules leave those fields as ``None``.
    """

    value: float
    method: str
    intervals: int
    evaluations: int
    iterations: int | None = None
    converged: bool = True
    residual: float | None = None
    tolerance: float | None = None

    def __str__(self) -> str:
        return (
            f"{self.method}: value={self.value:.12g}, "
            f"intervals={self.intervals}, evaluations={self.evaluations}"
        )


@dataclass(frozen=True, slots=True, eq=False)
class LinearResult:
    """Outcome of an iterative linear solver."""

    solution: np.ndarray
    iterations: int
    converged: bool
    residual: float
    tolerance: float
    method: str
    history: tuple[np.ndarray, ...] | None = None

    def __str__(self) -> str:
        status = "converged" if self.converged else "not converged"
        return (
            f"{self.method} ({status}): iterations={self.iterations}, "
            f"residual={self.residual:.3e}, tolerance={self.tolerance:.3e}"
        )


@dataclass(frozen=True, slots=True, eq=False)
class ODEResult:
    """Discrete solution of an initial-value problem.

    ``y`` has shape ``(n,)`` for a scalar equation and ``(n, dim)`` for a
    system. ``t[0]`` is the initial time and ``t[-1]`` is the final time.
    """

    t: np.ndarray
    y: np.ndarray
    method: str
    accepted_steps: int
    rejected_steps: int

    def __str__(self) -> str:
        return (
            f"{self.method}: steps={self.accepted_steps} "
            f"(rejected={self.rejected_steps}), "
            f"t=[{self.t[0]:.6g}, {self.t[-1]:.6g}]"
        )


@dataclass(frozen=True, slots=True, eq=False)
class FitResult:
    """Polynomial least-squares fit.

    ``coefficients`` are ordered from degree 0 upward, so the model is
    ``c[0] + c[1] x + ... + c[d] x**d``.
    """

    coefficients: np.ndarray
    residual_norm: float
    r_squared: float
    degree: int

    def __call__(self, x: ArrayLike) -> float | np.ndarray:
        """Evaluate the fitted polynomial at ``x``."""
        coeff = self.coefficients
        x_arr = np.asarray(x, dtype=float)
        value = np.empty(np.shape(x_arr), dtype=float)
        value[...] = coeff[-1]
        for term in coeff[-2::-1]:
            value = value * x_arr + term
        if np.ndim(x) == 0:
            return float(value)
        return value

    def __str__(self) -> str:
        return (
            f"polynomial degree {self.degree}: "
            f"residual_norm={self.residual_norm:.3e}, r_squared={self.r_squared:.6f}"
        )


@dataclass(frozen=True, slots=True, eq=False)
class EigenResult:
    """A single eigenpair computed by an iterative method.

    The eigenvector is scaled to unit Euclidean norm and oriented so that its
    entry of largest magnitude is positive.
    """

    eigenvalue: float
    eigenvector: np.ndarray
    iterations: int
    converged: bool
    residual: float
    tolerance: float
    method: str
    history: tuple[float, ...]

    def __str__(self) -> str:
        status = "converged" if self.converged else "not converged"
        return (
            f"{self.method} ({status}): eigenvalue={self.eigenvalue:.12g}, "
            f"iterations={self.iterations}, residual={self.residual:.3e}"
        )
